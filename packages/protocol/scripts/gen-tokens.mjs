// Genere les tokens de design depuis tokens/ds.json vers les trois cibles :
// app/src/theme/ds.ts (Expo), app/targets/watch/DSTokens.swift (montre) et,
// quand KOVA_REPO est defini, $KOVA_REPO/src/window/ds_tokens.rs (fenetre Kova).
// Regenere a chaque `npm run build` a la racine, et `protocol.test.ts` verifie
// que les fichiers sur disque sont a jour.
import { readFileSync, writeFileSync } from 'node:fs';
import { argv, env, stdout } from 'node:process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export const TOKENS_SOURCE = resolve(here, '../tokens/ds.json');
export const TS_TARGET = resolve(here, '../../../app/src/theme/ds.ts');
export const SWIFT_TARGET = resolve(here, '../../../app/targets/watch/DSTokens.swift');

const HEADER =
  'GENERATED by packages/protocol/scripts/gen-tokens.mjs from tokens/ds.json, do not edit';

/** Cible Rust, seulement quand KOVA_REPO pointe le depot de la fenetre Kova. */
export function rustTarget(repo = env.KOVA_REPO) {
  return repo ? resolve(repo, 'src/window/ds_tokens.rs') : null;
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const tsKey = (name) => (IDENTIFIER.test(name) ? name : JSON.stringify(name));
const f3 = (value) => value.toFixed(3);
const f1 = (value) => value.toFixed(1);

/** `bgInput` -> `BG_INPUT`, `selBg` -> `SEL_BG`, `b2` -> `B2`. */
const rustConst = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();

/** Rend [r, g, b, a] dans [0, 1] depuis `#RRGGBB` ou `rgba(r,g,b,a)`. */
function parseColor(value) {
  const hex = /^#([0-9A-Fa-f]{6})$/.exec(value);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255, 1];
  }
  const rgba = /^rgba\(([\d.]+),([\d.]+),([\d.]+),([\d.]+)\)$/.exec(value);
  if (!rgba) throw new Error(`couleur non reconnue : ${value}`);
  return [Number(rgba[1]) / 255, Number(rgba[2]) / 255, Number(rgba[3]) / 255, Number(rgba[4])];
}

export function renderTs(tokens) {
  const colors = (mode) =>
    Object.entries(tokens.colors)
      .map(([name, color]) => `    ${tsKey(name)}: '${color[mode]}',`)
      .join('\n');
  const tagDots = (mode) =>
    Object.entries(tokens.tagDots)
      .map(([name, color]) => `    ${tsKey(name)}: '${color[mode]}',`)
      .join('\n');
  const radii = Object.entries(tokens.radii)
    .map(([name, value]) => `    ${tsKey(name)}: ${value},`)
    .join('\n');
  const type = Object.entries(tokens.type)
    .map(([name, value]) => `    ${tsKey(name)}: [${value[0]}, ${value[1]}],`)
    .join('\n');

  return `// ${HEADER}
export const ds = {
  dark: {
${colors('dark')}
  },
  light: {
${colors('light')}
  },
  tagDots: {
    dark: {
${tagDots('dark')}
    },
    light: {
${tagDots('light')}
    },
  },
  radii: {
${radii}
  },
  type: {
${type}
  },
  font: '${tokens.font}',
} as const;
`;
}

export function renderSwift(tokens) {
  const colors = Object.entries(tokens.colors)
    .map(([name, color]) => {
      const [r, g, b, a] = parseColor(color.dark);
      return `    static let ${name} = Color(red: ${f3(r)}, green: ${f3(g)}, blue: ${f3(b)}, opacity: ${f3(a)})`;
    })
    .join('\n');

  return `// ${HEADER}
import SwiftUI

enum DS {
${colors}

    static func font(_ size: CGFloat, weight: Font.Weight = .regular) -> Font {
        let name: String
        switch weight {
        case .medium: name = "${tokens.font}-Medium"
        case .semibold: name = "${tokens.font}-SemiBold"
        case .bold: name = "${tokens.font}-Bold"
        default: name = "${tokens.font}-Regular"
        }
        return .custom(name, size: size)
    }
}
`;
}

export function renderRust(tokens) {
  const colors = (mode, indent) =>
    Object.entries(tokens.colors)
      .map(([name, color]) => {
        const [r, g, b, a] = parseColor(color[mode]);
        return `${indent}pub const ${rustConst(name)}: [f32; 4] = [${f3(r)}, ${f3(g)}, ${f3(b)}, ${f3(a)}];`;
      })
      .join('\n');
  const tagDots = (mode) =>
    Object.entries(tokens.tagDots)
      .map(([name, color]) => {
        const [r, g, b, a] = parseColor(color[mode]);
        return `        pub const ${rustConst(name)}: [f32; 4] = [${f3(r)}, ${f3(g)}, ${f3(b)}, ${f3(a)}];`;
      })
      .join('\n');
  const radii = Object.entries(tokens.radii)
    .map(([name, value]) => `pub const RADIUS_${rustConst(name)}: f64 = ${f1(value)};`)
    .join('\n');
  const type = Object.entries(tokens.type)
    .map(
      ([name, value]) =>
        `pub const TYPE_${rustConst(name)}: (f64, f64) = (${f1(value[0])}, ${f1(value[1])});`,
    )
    .join('\n');

  return `// ${HEADER}

#[allow(dead_code)]
pub mod dark {
${colors('dark', '    ')}
}

#[allow(dead_code)]
pub mod light {
${colors('light', '    ')}
}

#[allow(dead_code)]
pub mod tag_dots {
    #[allow(dead_code)]
    pub mod dark {
${tagDots('dark')}
    }

    #[allow(dead_code)]
    pub mod light {
${tagDots('light')}
    }
}

${radii}

${type}
`;
}

function run() {
  const tokens = JSON.parse(readFileSync(TOKENS_SOURCE, 'utf8'));
  const targets = [
    [TS_TARGET, renderTs(tokens)],
    [SWIFT_TARGET, renderSwift(tokens)],
  ];
  const rust = rustTarget();
  if (rust) targets.push([rust, renderRust(tokens)]);

  for (const [target, next] of targets) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      /* premier passage */
    }
    if (current !== next) {
      writeFileSync(target, next);
      stdout.write(`tokens : ${target} regenere\n`);
    }
  }
}

if (argv[1] && resolve(argv[1]) === fileURLToPath(import.meta.url)) run();
